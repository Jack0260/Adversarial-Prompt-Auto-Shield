function randomId(): string {
  return `${Date.now().toString(36)}-${Math.random().toString(36).substring(2, 9)}`;
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function randomScore(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

export function generateThreatEvent(): ThreatEvent {
  const isSystem = Math.random() < 0.15;

  if (isSystem) {
    const sys = pick(SYSTEM_EVENTS);
    return {
      id: randomId(),
      timestamp: Date.now(),
      type: sys.type,
      severity: sys.severity,
      status: sys.status,
      source: 'shield-internal',
      threatScore: sys.score,
      description: sys.description,
      details: 'Auto-generated by the shield monitoring subsystem during routine operations.',
      flaggedPhrases: [],
      techniqueBreakdown: [],
    };
  }

  const inputText = pick(SAMPLE_INJECTION_PROMPTS);
  const analysis = analyzeInput(inputText);
  const noise = randomScore(-10, 10);
  const threatScore = Math.max(0, Math.min(100, analysis.threatScore + noise));
  const severity = getSeverity(threatScore);
  const source = pick(THREAT_SOURCES);

  const status: ThreatStatus =
    threatScore >= 70 ? 'blocked' : threatScore >= 35 ? 'quarantined' : 'allowed';

  const driftVector = analysis.drift;

  return {
    id: randomId(),
    timestamp: Date.now(),
    type: analysis.threatScore >= 35 ? 'injection' : 'drift',
    severity,
    status,
    source,
    threatScore,
    description: truncate(inputText, 120),
    details: `Detected via semantic vector drift analysis. Drift score: ${driftVector.overall}/100. Source: ${source}. Input analyzed in ${Math.floor(Math.random() * 40 + 5)}ms.`,
    flaggedPhrases: analysis.flaggedPhrases,
    techniqueBreakdown: analysis.techniques.filter((t) => t.matched),
    inputText,
    driftVector,
  };
}

function truncate(s: string, max: number): string {
  if (s.length <= max) return s;
  return s.substring(0, max) + '...';
}

export function generateBurst(count: number): ThreatEvent[] {
  const events: ThreatEvent[] = [];
  for (let i = 0; i < count; i++) {
    const evt = generateThreatEvent();
    evt.timestamp = Date.now() - (count - i) * Math.floor(Math.random() * 3000 + 500);
    events.push(evt);
  }
  return events;
}
